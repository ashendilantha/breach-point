import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";
import { api } from "../lib/api";
import { Badge, Button, Card, CardHeader, Field, PageHead, inputCls } from "../components/ui";

export default function Settings() {
  const qc = useQueryClient();
  const providers = useQuery({ queryKey: ["providers"], queryFn: api.providersHealth });
  const scenarios = useQuery({ queryKey: ["scenarios"], queryFn: api.scenarios });
  const reset = useMutation({
    mutationFn: (runDemo: boolean) => api.demoReset(runDemo),
    onSuccess: () => qc.invalidateQueries(),
  });
  const [showScenario, setShowScenario] = useState(false);
  const [s, setS] = useState({
    id: "", name: "", category: "direct_injection", difficulty: "medium",
    user_task: "", content_type: "email", untrusted_content: "",
    attack_objective: '{"type": "tool_execution", "tool": "send_email"}',
    expected_legitimate: "", expected_legitimate_tools: "list_emails, read_email, summarize_email",
    expected_policy: "", success_criteria: "", severity: "medium",
  });
  const [err, setErr] = useState("");

  const createScenario = useMutation({
    mutationFn: () => {
      let obj: Record<string, unknown> = {};
      try { obj = JSON.parse(s.attack_objective); } catch { throw new Error("Attack objective must be valid JSON."); }
      return api.createScenario({
        ...s,
        attack_objective: obj,
        expected_legitimate_tools: s.expected_legitimate_tools.split(",").map((x) => x.trim()).filter(Boolean),
      });
    },
    onSuccess: () => { qc.invalidateQueries({ queryKey: ["scenarios"] }); setShowScenario(false); setErr(""); },
    onError: (e) => setErr((e as Error).message),
  });

  return (
    <div>
      <PageHead title="Settings" sub="Providers, demo data, and scenario management." />

      <div className="grid gap-4 lg:grid-cols-2">
        <Card>
          <CardHeader title="Model providers" sub="Credentials live in backend environment variables — never in the browser." />
          <div className="grid gap-3 px-5 py-4">
            {(providers.data?.providers ?? []).map((p) => (
              <div key={p.provider} className="rounded-md border border-ink-700 p-3 text-[13px]">
                <div className="flex items-center gap-2">
                  <span className="font-mono font-semibold">{p.provider}</span>
                  <Badge value={p.status === "ok" ? "approved" : p.status === "unconfigured" ? "pending" : "error"} label={p.status} />
                  {p.model && <span className="font-mono text-[12px] text-[#a7adbb]">{p.model}</span>}
                </div>
                {p.note && <p className="mt-1 text-[12px] text-[#a7adbb]">{p.note}</p>}
              </div>
            ))}
            <p className="text-[12px] text-[#a7adbb]">
              Mock: deterministic naive-agent simulation, always available. Meta: set META_API_BASE_URL, META_API_KEY,
              and META_MODEL on the backend (see docs/meta-provider.md), then select provider "meta" on an agent.
            </p>
          </div>
        </Card>

        <Card>
          <CardHeader title="Demo dataset" sub="Reset wipes runs and reseeds. Destructive by design — local demo only." />
          <div className="grid gap-3 px-5 py-4">
            <div className="flex gap-2">
              <Button onClick={() => reset.mutate(true)} disabled={reset.isPending}>
                {reset.isPending ? "Resetting…" : "Reset + run demo evidence"}
              </Button>
              <Button variant="outline" onClick={() => reset.mutate(false)} disabled={reset.isPending}>
                Reset (seed only)
              </Button>
            </div>
            {reset.data && <p className="text-[13px] text-[#4cc38a]">Seeded {JSON.stringify(reset.data.seeded)} · demo runs {reset.data.demo_run_ids.join(", ")}. {reset.data.note}</p>}
            <p className="text-[12px] text-[#a7adbb]">Demo evidence is generated by actual execution through the firewall and verifier — never hand-written.</p>
          </div>
        </Card>
      </div>

      <Card className="mt-4">
        <CardHeader
          title="Attack scenarios"
          sub={`${scenarios.data?.length ?? 0} scenarios stored in the database. New cases work immediately — no code changes.`}
          right={<Button small variant="outline" onClick={() => setShowScenario((x) => !x)}>{showScenario ? "Cancel" : "New scenario"}</Button>}
        />
        {showScenario && (
          <div className="grid gap-3 border-b border-ink-700 px-5 py-4">
            <div className="grid gap-3 md:grid-cols-3">
              <Field label="Scenario ID"><input className={inputCls} value={s.id} onChange={(e) => setS({ ...s, id: e.target.value })} placeholder="G-custom-1" /></Field>
              <Field label="Name"><input className={inputCls} value={s.name} onChange={(e) => setS({ ...s, name: e.target.value })} /></Field>
              <Field label="Category">
                <select className={inputCls} value={s.category} onChange={(e) => setS({ ...s, category: e.target.value })}>
                  {["direct_injection", "indirect_email", "webpage", "document", "benign_control", "unknown_tool"].map((c) => (
                    <option key={c} value={c}>{c}</option>
                  ))}
                </select>
              </Field>
            </div>
            <Field label="Original user task"><input className={inputCls} value={s.user_task} onChange={(e) => setS({ ...s, user_task: e.target.value })} /></Field>
            <Field label="Untrusted content"><textarea className={inputCls} rows={3} value={s.untrusted_content} onChange={(e) => setS({ ...s, untrusted_content: e.target.value })} /></Field>
            <div className="grid gap-3 md:grid-cols-2">
              <Field label="Attack objective (JSON)"><input className={inputCls} value={s.attack_objective} onChange={(e) => setS({ ...s, attack_objective: e.target.value })} /></Field>
              <Field label="Legitimate tools (comma-sep)"><input className={inputCls} value={s.expected_legitimate_tools} onChange={(e) => setS({ ...s, expected_legitimate_tools: e.target.value })} /></Field>
            </div>
            <div className="grid gap-3 md:grid-cols-3">
              <Field label="Expected legitimate"><input className={inputCls} value={s.expected_legitimate} onChange={(e) => setS({ ...s, expected_legitimate: e.target.value })} /></Field>
              <Field label="Expected policy"><input className={inputCls} value={s.expected_policy} onChange={(e) => setS({ ...s, expected_policy: e.target.value })} /></Field>
              <Field label="Success criteria"><input className={inputCls} value={s.success_criteria} onChange={(e) => setS({ ...s, success_criteria: e.target.value })} /></Field>
            </div>
            {err && <p className="text-sm text-[#ff8a8a]">{err}</p>}
            <div><Button onClick={() => createScenario.mutate()} disabled={createScenario.isPending || !s.id || !s.name || !s.user_task || !s.untrusted_content}>Create scenario</Button></div>
          </div>
        )}
        <table className="w-full text-left text-[13px]">
          <thead>
            <tr className="border-b border-ink-700 text-[12px] uppercase tracking-wide text-[#a7adbb]">
              <th className="px-5 py-2.5 font-medium">ID</th>
              <th className="px-3 py-2.5 font-medium">Name</th>
              <th className="px-3 py-2.5 font-medium">Category</th>
              <th className="px-3 py-2.5 font-medium">Severity</th>
            </tr>
          </thead>
          <tbody>
            {(scenarios.data ?? []).map((sc) => (
              <tr key={sc.id} className="border-b border-ink-800 last:border-0">
                <td className="px-5 py-2 font-mono text-[12px]">{sc.id}</td>
                <td className="px-3 py-2">{sc.name}</td>
                <td className="px-3 py-2 font-mono text-[12px]">{sc.category}</td>
                <td className="px-3 py-2 text-[#a7adbb]">{sc.severity}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </Card>
    </div>
  );
}
